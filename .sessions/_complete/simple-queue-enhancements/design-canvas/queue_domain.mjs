// Bundles the prompt-queue mod's own TypeScript for the canvas, unchanged, with the stand-ins in canvas_engine.js:
//   node queue_domain.mjs <worktree> <out.js> <fixtures.json>
// Each module's types are stripped by Node, its imports read from the modules bundled before it, and its exports
// kept for the screen as QueueCanvas.mod. The icons are taken from icon-button-view.tsx without its one JSX view,
// which the canvas draws as markup of its own. The fixtures (each scenario's Givens, replayed on the real cdd server's
// PromptQueue by build_explorer.py) become CanvasFixtures.
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [worktree, outfile, fixturesFile] = process.argv.slice(2);
const QUEUE = join(worktree, 'tools/prompt_queue/hooks/queue');
const HERE = dirname(fileURLToPath(import.meta.url));
// The modules in the order they import one another; each is named as the others import it.
const MODULES = [['./plan-steps', 'plan-steps.ts'], ['./queue-order', 'queue-order.ts'], ['./prompt-queue', 'prompt-queue.ts'], ['./icon-button-view', 'icon-button-view.tsx'], ['./queue-view', 'queue-view.tsx']];
// The one JSX view in icon-button-view.tsx, from its doc comment to its closing brace: the canvas draws icons itself.
const ICON_VIEW = /\/\*\*\n \* An image the person clicks[\s\S]*?\nexport function IconButtonView[\s\S]*?\n}\n/;
// From queue-view.tsx, which is JSX the canvas draws as markup: its column widths, step marks and icon choices, which
// are plain TypeScript, so the canvas shows the mod's own icons and tooltips.
const VIEW_PARTS = /^(?:const [A-Z_]+(?:: Icon)? = [^\n]*\n|function (?:stackIcon|playIcon|subAgentsIcon)\([\s\S]*?\n}\n)/gm;
const VIEW_IMPORTS = "import { ADD_SVG, CLEAR_SVG, PAUSE_SVG, PLAY_SVG, stackSvgOf, SUB_AGENTS_SVG } from './icon-button-view'\n";

// A file of the mod's, each line ending in a bare newline whichever endings it was saved with.
function lines(file) {
  return readFileSync(join(QUEUE, file), 'utf8').split('\r\n').join('\n');
}

function viewSource() {
  const parts = lines('queue-view.tsx').match(VIEW_PARTS) || [];
  return VIEW_IMPORTS + parts.map(part => 'export ' + part).join('');
}

function sourceOf(file) {
  if (file === 'queue-view.tsx') return viewSource();
  const text = lines(file);
  return file.endsWith('.tsx') ? text.replace(ICON_VIEW, '') : text;
}

function moduleOf(name, file) {
  const exported = [];
  const body = stripTypeScriptTypes(sourceOf(file), { mode: 'transform' })
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)'.*$/gm, (_line, names, from) =>
      `const {${names.replace(/\bas\b/g, ':')}} = modules['${from}'];`)
    .replace(/^export\s+(async\s+function|function|const|class|let)\s+([A-Za-z_$][\w$]*)/gm, (_line, kind, exportedName) => {
      exported.push(exportedName);
      return `${kind} ${exportedName}`;
    });
  return `modules['${name}'] = (function () {\n${body}\nreturn { ${exported.join(', ')} };\n})();\n`;
}

const engine = readFileSync(join(HERE, 'canvas_engine.js'), 'utf8');
const fixtures = readFileSync(fixturesFile, 'utf8');
const bundle = `// Generated by queue_domain.mjs from tools/prompt_queue/hooks/queue: do not edit.
(function () {
${engine}
const modules = { 'claude-code': claudeCode };
${MODULES.map(([name, file]) => moduleOf(name, file)).join('\n')}
const FIXTURES = ${fixtures};
window.QueueCanvas = { mod: Object.assign({}, modules['./prompt-queue'], modules['./plan-steps'], modules['./icon-button-view'], modules['./queue-view']), engine: (changed) => new CanvasEngine(changed) };
window.CanvasFixtures = {
  load: (story, scenario) => {
    const fixture = (FIXTURES.scenarios[story] || {})[scenario];
    return fixture ? Promise.resolve(fixture) : Promise.reject(new Error('No Givens for ' + story + ' › ' + scenario));
  },
  scenarios: (story) => Object.keys(FIXTURES.scenarios[story] || {}),
  examples: FIXTURES.examples,
  pasteFor: () => null,
  repositories: () => ({ queue: { chat: 'canvas-chat', prompts: [] }, view: {} }),
};
})();
`;
writeFileSync(outfile, bundle);
