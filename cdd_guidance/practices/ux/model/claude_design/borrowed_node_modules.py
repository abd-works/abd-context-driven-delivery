"""The node_modules holding an esbuild that a heavy spec's throwaway project borrows, rather than installing its own."""

from __future__ import annotations

from pathlib import Path

from harness.release.test_runs import main_checkout

# The apps the repository installs whose node_modules hold esbuild, from the repository's root.
_APPS_WITH_ESBUILD = ("harness/graph/app", "cdd_guidance/practices/stories/app")


class EsbuildNotInstalled(Exception):
    """No app of the checkout, nor of its main checkout, has its node_modules installed with esbuild."""

    def __init__(self, repo: Path) -> None:
        super().__init__(f"No node_modules with esbuild under {repo} or its main checkout; run npm install in {_APPS_WITH_ESBUILD[0]}.")
        self.repo = repo


def node_modules_with_esbuild(repo: Path) -> Path:
    """The node_modules of an app of repo that holds esbuild; for a ticket's worktree, which installs no app, the main
    checkout's, as scripts/test.ps1 takes the main checkout's venv."""
    main = main_checkout(repo)
    for checkout in [Path(repo), *([main] if main is not None else [])]:
        for app in _APPS_WITH_ESBUILD:
            modules = checkout / app / "node_modules"
            if (modules / "esbuild").is_dir():
                return modules
    raise EsbuildNotInstalled(Path(repo))
