class MissingIdentityError(ValueError):
    """A toolset's tools load one object by name, but its mark does not say which field of its data holds that name."""

    def __init__(self, toolset_name: str) -> None:
        super().__init__(f"{toolset_name} loads one object by name; add identity=<field>, one field for each argument of its loader, to its @language_adapter mark")


def schema_type(schema: Mapping[str, Any]) -> str:
    """The TypeScript type of one published JSON Schema."""
    if "anyOf" in schema:
        return " | ".join(schema_type(option) for option in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"{schema_type(schema.get('items', {}))}[]"
    if kind == "object":
        return _OPEN_DATA
    return _SCHEMA_TYPES.get(kind, "unknown")


def argument_schema(schema: Mapping[str, Any]) -> dict[str, Any]:
    """Only what checking a sent value needs from one published JSON Schema."""
    kept: dict[str, Any] = {"type": schema["type"]} if "type" in schema else {}
    if "items" in schema:
        kept["items"] = argument_schema(schema["items"])
    if "anyOf" in schema:
        kept["anyOf"] = [argument_schema(option) for option in schema["anyOf"]]
    return kept


def read_arguments_call(properties: Mapping[str, Any], required: list[str]) -> str:
    """Reads the named arguments from a request, typed and checked against their published schema."""
    shape = "; ".join(f"{name}{'' if name in required else '?'}: {schema_type(schema)}" for name, schema in properties.items())
    checks = json.dumps({name: argument_schema(schema) for name, schema in properties.items()})
    return f"readArguments<{{ {shape} }}>(request, {checks}, {json.dumps(required)})"


def input_kind(schema: Mapping[str, Any]) -> str:
    """The input a published argument type draws: text, a number, a checkbox, one string per line, or JSON."""
    if "anyOf" in schema:
        chosen = [option for option in schema["anyOf"] if option.get("type") != "null"]
        return input_kind(chosen[0]) if len(chosen) == 1 else "json"
    if schema.get("type") == "array" and schema.get("items", {}).get("type") == "string":
        return "list"
    return _SCHEMA_INPUTS.get(schema.get("type"), "json")


def label_of(name: str) -> str:
    """A Python name as a person reads it: `is_enabled` is "Is enabled"."""
    words = name.replace("_", " ")
    return words[:1].upper() + words[1:]


def spelled(name: str) -> str:
    """A Python argument name as a TypeScript parameter, kept clear of reserved words."""
    camel = Name(name).camel
    return f"{camel}Value" if camel in _RESERVED_WORDS else camel


def _sent_under_python_name(name: str) -> str:
    return name if spelled(name) == name else f"{name}: {spelled(name)}"


def _split_top_level(text: str, separator: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for character in text:
        depth += (character == "[") - (character == "]")
        if character == separator and depth == 0:
            parts.append(current.strip())
            current = ""
            continue
        current += character
    return [*parts, current.strip()]


def _in_list(type_text: str) -> str:
    return f"({type_text})[]" if " | " in type_text else f"{type_text}[]"


def _unwrapped(hint: object) -> object:
    """A hint without its `NotRequired` or `Annotated` wrapper: TypeScript types the field by what it holds."""
    while get_origin(hint) in (NotRequired, Annotated):
        hint = get_args(hint)[0]
    return hint


def is_shape(hint: object) -> bool:
    """A class that marks properties as its data."""
    return isinstance(hint, type) and bool(data_fields_of(hint))


def shape_name(shape: type) -> str:
    """A class's data is named after it, so `Ticket` sends `TicketData`."""
    return f"{shape.__name__}Data"


def _subclasses(cls: type) -> list[type]:
    return [found for sub in cls.__subclasses__() for found in (sub, *_subclasses(sub))]


def shape_fields(shape: type, names: Mapping[str, Any]) -> dict[str, object]:
    """Each field's type by its name in the data. A field only some kinds of a class have, such as a stage's WIP
    limit on a column, is optional, so one type holds every kind. names resolves the types a module imports only
    for type checking."""
    fields = {key: _return_hint(field, names) for key, field in data_fields_of(shape).items()}
    for sub in _subclasses(shape):
        for key, field in data_fields_of(sub).items():
            fields.setdefault(key, NotRequired[_return_hint(field, names)])
    return fields


def _return_hint(field: property, names: Mapping[str, Any]) -> object:
    getter = field.fget
    return get_type_hints(getter, globalns=getter.__globals__, localns=dict(names), include_extras=True)["return"]


def is_source_file(hint: object) -> bool:
    """A field marked `Annotated[str, SourceFile]`, which holds a path the file manager reads."""
    if get_origin(hint) is NotRequired:
        hint = get_args(hint)[0]
    return get_origin(hint) is Annotated and SourceFile in get_args(hint)[1:]


class TypeScriptOperation:
    """One MCP tool, as the server adapter, the browser adapter, and the route between them each write it."""

    def __init__(self, tool: AgentTool, owner: TypeScriptToolset) -> None:
        self._owner = owner
        self.mcp_name = tool.mcp_name
        self.name = Name(tool.name).camel
        self.is_static = inspect.ismethod(tool.callable)
        self.identity = owner.identity_of(tool)
        schema = tool.input_schema
        self.properties = {name: value for name, value in schema["properties"].items() if name not in self.identity}
        self.required = [name for name in schema.get("required", []) if name in self.properties]
        self.result = owner.result_of(tool)
        self.path_tail = Name(tool.name).kebab
        self.label = label_of(tool.name)
        self.marked_edits = Edits.fields_of(tool.callable)

    @property
    def returns_itself(self) -> bool:
        """An instance operation whose tool answers with the object's own data takes on that state."""
        return not self.is_static and self.result == self._owner.data_name

    @property
    def _parameters(self) -> str:
        return ", ".join(f"{spelled(name)}{'' if name in self.required else '?'}: {schema_type(value)}" for name, value in self.properties.items())

    @property
    def _arguments(self) -> list[str]:
        return [_sent_under_python_name(name) for name in self.properties]

    def adapter_lines(self) -> list[str]:
        held = [f"{name}: this.#{Name(name).camel}" for name in self.identity]
        arguments = f"{{ {', '.join([*held, *self._arguments])} }}" if held or self.properties else "{}"
        if self.is_static:
            parameters = ", ".join(filter(None, ["cdd: CddConnection", self._parameters]))
            return self._method(f"static {self.name}({parameters})", f"cdd.call<{self.result}>('{self.mcp_name}', {arguments})")
        return self._method(f"{self.name}({self._parameters})", f"this.cdd.call<{self.result}>('{self.mcp_name}', {arguments})")

    def client_lines(self) -> list[str]:
        body = f"{{ {', '.join(self._arguments)} }}" if self.properties else "{}"
        if self.is_static:
            parameters = ", ".join(filter(None, ["api: CddApi", self._parameters]))
            return self._posted(f"static {self.name}({parameters})", f"api.post<{self.result}>('{self._route_path(None)}', {body})")
        address = "/".join(f"${{encodeURIComponent(this.#{Name(name).camel})}}" for name in self.identity) or None
        return self._posted(f"{self.name}({self._parameters})", f"this.api.post<{self.result}>(`{self._route_path(address)}`, {body})")

    def _method(self, signature: str, call: str) -> list[str]:
        if self.returns_itself:
            return ["", f"  async {signature}: Promise<this> {{", f"    return this.changed(await {call})", "  }"]
        return ["", f"  {signature}: Promise<{self.result}> {{", f"    return {call}", "  }"]

    def _posted(self, signature: str, call: str) -> list[str]:
        """A browser call answers null once the page has shown its failure, and the object then keeps its state."""
        if self.returns_itself:
            return ["", f"  async {signature}: Promise<this | null> {{", f"    const state = await {call}", "    return state ? this.changed(state) : null", "  }"]
        return ["", f"  {signature}: Promise<{self.result} | null> {{", f"    return {call}", "  }"]

    def route_lines(self) -> list[str]:
        node = self._owner.adapter_name
        sent = ", ".join(f"sent.{name}" for name in self.properties)
        if self.is_static:
            target = f"{node}.{self.name}(cdd{', ' if sent else ''}{sent})"
        elif self.identity:
            target = f"{node}.fromRequest(cdd, request).{self.name}({sent})"
        else:
            target = f"new {node}(cdd).{self.name}({sent})"
        path = self._route_path("/".join(f":{name}" for name in self.identity) or None)
        if not self.properties:
            return [f"  {{ path: '{path}', run: (cdd, request) => {target} }},"]
        read = read_arguments_call(self.properties, self.required)
        return ["  {", f"    path: '{path}',", "    run: (cdd, request) => {", f"      const sent = {read}", f"      return {target}", "    },", "  },"]

    def _route_path(self, address: str | None) -> str:
        return "/".join(["", self._owner.slug, *([address] if address else []), self.path_tail])


class TypeScriptToolset:
    """One marked toolset, written as one TypeScript file of its generated classes and one of its starting-point views."""

    def __init__(self, toolset: Any, tools: list[AgentTool], folder: Path, peers: dict[str, TypeScriptToolset]) -> None:
        self._toolset = toolset
        self._tools = sorted(tools, key=lambda tool: tool.mcp_name)
        self._folder = PurePosixPath(folder.as_posix())
        self._peers = peers
        self._shapes: dict[str, type] = {}
        self._imports: set[tuple[str, str]] = set()
        self.name = type(toolset).__name__
        self.slug = toolset.slug
        self.identity_fields = LanguageAdapter.identity_fields_of(type(toolset))

    @property
    def file_path(self) -> PurePosixPath:
        return self._folder / f"{self.slug}.ts"

    @property
    def views_file_path(self) -> PurePosixPath:
        return self._folder / f"{self.slug}{_VIEWS_SUFFIX}.tsx"

    @property
    def adapter_name(self) -> str:
        return f"{self.name}Adapter"

    @property
    def client_name(self) -> str:
        return f"{self.name}ClientGenerated"

    @property
    def data_name(self) -> str:
        return shape_name(self._data_shape) if self._data_shape else f"{self.name}Data"

    @property
    def _routes_name(self) -> str:
        return f"{Name(self.slug).camel}Routes"

    @property
    def _data_shape(self) -> type | None:
        """The toolset's class when it marks properties as its data."""
        toolset_class = type(self._toolset)
        return toolset_class if data_fields_of(toolset_class) else None

    @property
    def peer_classes(self) -> dict[str, type]:
        """Every marked toolset's class by name, for the types a module imports only for type checking."""
        return {peer.name: type(peer._toolset) for peer in self._peers.values()}

    def _shape_named(self, name: str, function: Any) -> type | None:
        found = vars(sys.modules[function.__module__]).get(name)
        return found if is_shape(found) else None

    def render(self) -> dict[PurePosixPath, str]:
        # The operations come first: writing them is what names the imports and nested shapes the files need.
        operations = [TypeScriptOperation(tool, self) for tool in self._tools]
        identity = self._identity_name()
        if len(identity) != len(self.identity_fields):
            raise MissingIdentityError(self.name)
        adapter = self._adapter_class(operations, identity)
        routes = self._routes(operations)
        client = self._client_class(operations, identity)
        data = self._data_lines()
        base = self._base_class()
        classes = [*self._header(), "", *data, *base, "", *client, "", *adapter, "", *routes]
        views = TypeScriptViews(self, operations).render()
        return {self.file_path: self._joined(classes), self.views_file_path: self._joined(views)}

    def _joined(self, lines: list[str]) -> str:
        return "\n".join(lines).rstrip() + "\n"

    def _header(self) -> list[str]:
        """The connection comes in only as a type, so a browser can load this file and runs nothing of Node."""
        return [
            _NOTE.format(source=f"the @mcp operations of {self.name}"),
            f"import type {{ CddConnection }} from '{self.relative(_CONNECTION_FILE)}'",
            f"import {{ CddNotReadError, readArguments, type CddApi, type CddRequest, type CddRoute }} from '{self.relative(_SHARED_FILE)}'",
            *self._peer_import_lines(),
        ]

    def relative(self, file_name: str) -> str:
        return os.path.relpath(file_name.removesuffix(".ts"), self._folder.as_posix()).replace("\\", "/")

    def _peer_import_lines(self) -> list[str]:
        grouped: dict[str, list[str]] = {}
        for peer, name in sorted(self._imports):
            grouped.setdefault(peer, []).append(name)
        return [self._import_line(peer, names) for peer, names in grouped.items()]

    def _import_line(self, peer_name: str, names: list[str]) -> str:
        peer = self._peers[peer_name]
        path = os.path.relpath(peer.file_path.with_suffix("").as_posix(), self._folder.as_posix()).replace("\\", "/")
        return f"import type {{ {', '.join(names)} }} from '{path if path.startswith('.') else f'./{path}'}'"

    def _data_lines(self) -> list[str]:
        root = self._data_shape
        if root is None:
            return [f"export type {self.data_name} = {_OPEN_DATA}", ""]
        self._shapes[shape_name(root)] = root
        lines: list[str] = []
        written: set[str] = set()
        while unwritten := [name for name in self._shapes if name not in written]:
            for name in unwritten:
                written.add(name)
                lines.extend(self._shape_lines(self._shapes[name]))
        return lines

    def _shape_lines(self, shape: type) -> list[str]:
        fields = [self._field_line(name, hint) for name, hint in shape_fields(shape, self.peer_classes).items()]
        return [f"export type {shape_name(shape)} = {{", *fields, "}", ""]

    def _field_line(self, name: str, hint: object) -> str:
        if get_origin(hint) is NotRequired:
            return f"  {name}?: {self._hint_type(get_args(hint)[0])}"
        return f"  {name}: {self._hint_type(hint)}"

    def _hint_type(self, hint: object) -> str:
        hint = _unwrapped(hint)
        if is_shape(hint):
            return self._shape_reference(hint)
        origin = get_origin(hint)
        if origin is Literal:
            return " | ".join(json.dumps(word).replace('"', "'") for word in get_args(hint))
        if origin in (Union, types.UnionType):
            return " | ".join(self._hint_type(option) for option in get_args(hint))
        if origin is list:
            return _in_list(self._hint_type(get_args(hint)[0]))
        if origin is dict:
            return f"Record<string, {self._hint_type(get_args(hint)[1])}>"
        return _SCALAR_TYPES.get(hint, "unknown")

    def _shape_reference(self, shape: type) -> str:
        name = shape_name(shape)
        for peer in self._peers.values():
            if peer._data_shape is shape:
                if peer is not self:
                    self._imports.add((peer.name, name))
                return name
        self._shapes.setdefault(name, shape)
        return name

    def _base_class(self) -> list[str]:
        """The shared base: state and getters, no calls. Nothing uses it directly; code holds one of its subtypes."""
        getters = [line for name, hint in self.data_fields().items() for line in self._getter(name, hint)]
        return [
            f"export class {self.name} {{",
            f"  #state: {self.data_name} | null",
            "  readonly #listeners = new Set<() => void>()",
            "",
            f"  constructor(state: {self.data_name} | null) {{",
            "    this.#state = state",
            "  }",
            "",
            f"  toJSON(): {self.data_name} {{",
            "    return this.#read()",
            "  }",
            *getters,
            "",
            "  // A view subscribes here so it draws the state an operation returned; the answer unsubscribes.",
            "  onChanged(listener: () => void): () => void {",
            "    this.#listeners.add(listener)",
            "    return () => {",
            "      this.#listeners.delete(listener)",
            "    }",
            "  }",
            "",
            f"  protected changed(state: {self.data_name}): this {{",
            "    this.#state = state",
            "    for (const listener of this.#listeners) listener()",
            "    return this",
            "  }",
            "",
            "  // A server adapter is built from the name a request carries, before Python has sent its state.",
            f"  #read(): {self.data_name} {{",
            f"    if (!this.#state) throw new CddNotReadError('{self.slug}')",
            "    return this.#state",
            "  }",
            "}",
        ]

    def data_fields(self) -> dict[str, object]:
        return shape_fields(self._data_shape, self.peer_classes) if self._data_shape else {}

    def _getter(self, name: str, hint: object) -> list[str]:
        optional = get_origin(hint) is NotRequired
        shown = self._hint_type(get_args(hint)[0] if optional else hint)
        return ["", f"  get {Name(name).camel}(): {shown}{' | undefined' if optional else ''} {{", f"    return this.#read().{name}", "  }"]

    def _adapter_class(self, operations: list[TypeScriptOperation], identity: tuple[str, ...]) -> list[str]:
        held = "".join(f", {Name(name).camel}: string" for name in identity)
        return [
            f"export class {self.adapter_name} extends {self.name} {{",
            *_identity_fields(identity),
            f"  constructor(protected readonly cdd: CddConnection{held}, state: {self.data_name} | null = null) {{",
            "    super(state)",
            *_identity_kept(identity),
            "  }",
            *self._from_request(identity),
            *[line for operation in operations for line in operation.adapter_lines()],
            "}",
        ]

    def _from_request(self, identity: tuple[str, ...]) -> list[str]:
        """Builds the server adapter for the object a request names, so an application never parses the address."""
        if not identity:
            return []
        read = read_arguments_call({name: {"type": "string"} for name in identity}, list(identity))
        named = ", ".join(f"named.{name}" for name in identity)
        return [
            "",
            f"  static fromRequest(cdd: CddConnection, request: CddRequest): {self.adapter_name} {{",
            f"    const named = {read}",
            f"    return new {self.adapter_name}(cdd, {named})",
            "  }",
        ]

    def _client_class(self, operations: list[TypeScriptOperation], identity: tuple[str, ...]) -> list[str]:
        held = "".join(f", {Name(name).camel}: string = state?.{field} ?? ''" for name, field in zip(identity, self.identity_fields))
        return [
            f"export class {self.client_name} extends {self.name} {{",
            *_identity_fields(identity),
            f"  constructor(readonly api: CddApi, state: {self.data_name} | null = null{held}) {{",
            "    super(state)",
            *_identity_kept(identity),
            "  }",
            *self._named(identity),
            *[line for operation in operations for line in operation.client_lines()],
            "}",
        ]

    def _named(self, identity: tuple[str, ...]) -> list[str]:
        """Page code that knows only an object's name can still act on it, before it has read the object."""
        if not identity:
            return []
        names = [Name(name).camel for name in identity]
        return [
            "",
            f"  static named(api: CddApi, {', '.join(f'{name}: string' for name in names)}): {self.client_name} {{",
            f"    return new {self.client_name}(api, null, {', '.join(names)})",
            "  }",
        ]

    def _routes(self, operations: list[TypeScriptOperation]) -> list[str]:
        """One route for each tool, so the browser adapter and the server adapter meet at a path neither side writes."""
        return [f"export const {self._routes_name}: CddRoute[] = [", *[line for operation in operations for line in operation.route_lines()], "]"]

    def _identity_name(self) -> tuple[str, ...]:
        return next(filter(None, map(self.identity_of, self._tools)), ())

    def identity_of(self, tool: AgentTool) -> tuple[str, ...]:
        """The arguments that name the object, its loader's: a loader with none, like the current board's, names none."""
        if not OnSubject.marks(tool.callable):
            return ()
        load = AgentToolSet.tool_subject_of(type(self._toolset))
        return tuple(inspect.signature(load).parameters)

    def result_of(self, tool: AgentTool) -> str:
        annotation = inspect.signature(tool.callable).return_annotation
        text = annotation.__name__ if isinstance(annotation, type) else str(annotation).replace("typing.", "")
        return self._text_type(text, tool.callable)

    def _text_type(self, text: str, function: Any) -> str:
        members = _split_top_level(text, "|")
        if len(members) > 1:
            return " | ".join(self._text_type(member, function) for member in members)
        if text.startswith("list["):
            return _in_list(self._text_type(text[5:-1], function))
        if text.startswith("dict["):
            return f"Record<string, {self._text_type(_split_top_level(text[5:-1], ',')[1], function)}>"
        if text in self._peers:
            return self._peer_data(text)
        shape = self._shape_named(text, function)
        return self._shape_reference(shape) if shape else _SCALAR_NAMES.get(text, "unknown")

    def _peer_data(self, name: str) -> str:
        peer = self._peers[name]
        if peer is not self:
            self._imports.add((name, peer.data_name))
        return peer.data_name


class TypeScriptViews:
    """Starting-point React views of one object: never a finished page, always composed or copied by the application."""

    def __init__(self, owner: TypeScriptToolset, operations: list[TypeScriptOperation]) -> None:
        self._owner = owner
        self._operations = operations
        self._fields = owner.data_fields()
        self._edits = {field: edit for field in self._fields if (edit := self._edit_of(field))}
        self._source_files = [field for field, hint in self._fields.items() if is_source_file(hint)]

    def render(self) -> list[str]:
        return [*self._header(), "", *self._hook(), "", *self._view(), *self._new_view()]

    def _header(self) -> list[str]:
        owner = self._owner
        return [
            _NOTE.format(source=f"the @mcp operations of {owner.name}"),
            _JSX_PRAGMA,
            "import { useEffect, useReducer, type ReactNode } from 'react'",
            "",
            f"import type {{ CddApi }} from '{owner.relative(_SHARED_FILE)}'",
            f"import {{ EditableField, OperationForm, ReadOnlyField }} from '{owner.relative(_VIEWS_FILE.removesuffix('x'))}'",
            *([f"import {{ SourceField }} from '{owner.relative(_FILES_FILE.removesuffix('x'))}'"] if self._source_files else []),
            f"import {{ {owner.client_name}, type {owner.name}, type {owner.data_name} }} from './{owner.slug}'",
        ]

    def _hook(self) -> list[str]:
        name = self._owner.name
        return [
            f"// Draws the {name} again whenever its client takes on the state an operation returned.",
            f"export function use{name}<Client extends {name}>(client: Client): Client {{",
            "  const [, drawAgain] = useReducer((count: number) => count + 1, 0)",
            "  useEffect(() => client.onChanged(drawAgain), [client])",
            "  return client",
            "}",
        ]

    def _view(self) -> list[str]:
        owner = self._owner
        variable = Name(owner.slug).camel
        shown = [operation for operation in self._operations if not operation.is_static and operation not in [edit[0] for edit in self._edits.values()]]
        return [
            f"export type {owner.name}ViewProps = {{",
            f"  client: {owner.client_name}",
            f"  fields?: Partial<Record<{self._union(Name(field).camel for field in self._fields)}, (object: {owner.client_name}) => ReactNode>>",
            f"  operations?: Partial<Record<{self._union(operation.name for operation in shown)}, (object: {owner.client_name}) => ReactNode>>",
            "}",
            "",
            "// Each field is editable where a domain operation changes it and read-only elsewhere; every other operation is a button or a form.",
            f"export function {owner.name}ViewGenerated({{ client, fields = {{}}, operations = {{}} }}: {owner.name}ViewProps): ReactNode {{",
            f"  const {variable} = use{owner.name}(client)",
            "  return (",
            f"    <section className=\"cdd-view cdd-{owner.slug}\">",
            "      <div className=\"cdd-fields\">",
            *[f"        {self._field(field, hint, variable)}" for field, hint in self._fields.items()],
            "      </div>",
            "      <div className=\"cdd-operations\">",
            *[f"        {self._operation(operation, variable)}" for operation in shown],
            "      </div>",
            "    </section>",
            "  )",
            "}",
        ]

    def _union(self, names) -> str:
        quoted = [f"'{name}'" for name in names]
        return " | ".join(quoted) if quoted else "never"

    def _field(self, field: str, hint: object, variable: str) -> str:
        getter = Name(field).camel
        if field in self._source_files:
            fallback = self._source(field, variable)
        elif field in self._edits:
            fallback = self._editable(field, hint, variable)
        else:
            fallback = f"<ReadOnlyField label=\"{label_of(field)}\" value={{{variable}.{getter}}} />"
        return f"{{fields.{getter} ? fields.{getter}({variable}) : {fallback}}}"

    def _source(self, field: str, variable: str) -> str:
        """A file field opens the shared source view at the line, or the range, the same data holds."""
        place = [f" {Name(name).camel}={{{variable}.{Name(name).camel}}}" for name in ("line", "start_line", "end_line") if name in self._fields]
        return f"<SourceField api={{{variable}.api}} label=\"{label_of(field)}\" path={{{variable}.{Name(field).camel}}}{''.join(place)} />"

    def _editable(self, field: str, hint: object, variable: str) -> str:
        operation, argument = self._edits[field]
        sent = ", ".join(self._edit_argument(name, value, argument, variable) for name, value in operation.properties.items())
        save = f"value => {variable}.{operation.name}({sent})"
        return f"<EditableField label=\"{label_of(field)}\" kind=\"{self._hint_input(hint)}\" value={{{variable}.{Name(field).camel}}} onSave={{{save}}} />"

    def _edit_argument(self, name: str, schema: Mapping[str, Any], argument: str, variable: str) -> str:
        if name == argument:
            return f"value as {schema_type(schema)}"
        return f"{variable}.{Name(name).camel}" if name in self._fields else "undefined"

    def _operation(self, operation: TypeScriptOperation, variable: str) -> str:
        form = self._form(operation, f"{self._values(operation)} => {variable}.{operation.name}({self._sent(operation)})")
        return f"{{operations.{operation.name} ? operations.{operation.name}({variable}) : {form}}}"

    def _form(self, operation: TypeScriptOperation, run: str) -> str:
        shows = "" if operation.returns_itself else " showsResult"
        return f"<OperationForm label=\"{operation.label}\" inputs={{{self._inputs(operation)}}}{shows} onRun={{{run}}} />"

    def _values(self, operation: TypeScriptOperation) -> str:
        return "values" if operation.properties else "()"

    def _sent(self, operation: TypeScriptOperation) -> str:
        return ", ".join(f"values.{name} as {schema_type(schema)}" for name, schema in operation.properties.items())

    def _inputs(self, operation: TypeScriptOperation) -> str:
        inputs = [
            f"{{ name: '{name}', label: '{label_of(name)}', kind: '{input_kind(schema)}', isRequired: {'true' if name in operation.required else 'false'} }}"
            for name, schema in operation.properties.items()
        ]
        return f"[{', '.join(inputs)}]"

    def _new_view(self) -> list[str]:
        """The class operations that answer with an object of this kind, each as its own form."""
        owner = self._owner
        creators = [operation for operation in self._operations if operation.is_static and operation.result == owner.data_name]
        if not creators:
            return []
        return [
            "",
            f"export type {owner.name}NewViewProps = {{ api: CddApi; onCreated?: (state: {owner.data_name}) => void }}",
            "",
            f"export function {owner.name}NewViewGenerated({{ api, onCreated }}: {owner.name}NewViewProps): ReactNode {{",
            "  return (",
            f"    <section className=\"cdd-view cdd-new-{owner.slug}\">",
            *[f"      {self._creator(operation)}" for operation in creators],
            "    </section>",
            "  )",
            "}",
        ]

    def _creator(self, operation: TypeScriptOperation) -> str:
        call = f"{self._owner.client_name}.{operation.name}(api{', ' if operation.properties else ''}{self._sent(operation)})"
        return self._form(operation, f"async {self._values(operation)} => {{ const created = await {call}; if (created) onCreated?.(created); return created }}")

    def _edit_of(self, field: str) -> tuple[TypeScriptOperation, str] | None:
        """The operation that changes a field, and the argument carrying the new value, when it can be saved alone."""
        for operation in self._operations:
            if not operation.returns_itself:
                continue
            argument = self._argument_for(operation, field)
            if argument and all(name == argument or name in self._fields for name in operation.required):
                return operation, argument
        return None

    def _argument_for(self, operation: TypeScriptOperation, field: str) -> str | None:
        if field in operation.properties:
            return field
        if field in operation.marked_edits and len(operation.properties) == 1:
            return next(iter(operation.properties))
        return None

    def _hint_input(self, hint: object) -> str:
        hint = _unwrapped(hint)
        if get_origin(hint) in (Union, types.UnionType):
            chosen = [option for option in get_args(hint) if option is not type(None)]
            return self._hint_input(chosen[0]) if len(chosen) == 1 else "json"
        if get_origin(hint) is list and get_args(hint) == (str,):
            return "list"
        return _HINT_INPUTS.get(hint, "json")


class LanguageAdapterInstallation(Installation):
    """Records marked toolsets during the install walk, then writes them together, because their files import each other."""

    channel = "language-adapter"

    def __init__(self, ide: str, path: Path | str, toolset_ref: str = "", repo: Path | str | None = None) -> None:
        super().__init__(ide, path, toolset_ref, repo)
        self._recorded: list[Any] = []

    def record(self, toolset: Any) -> None:
        """Remember toolset when its class is marked for TypeScript."""
        if _TYPESCRIPT in LanguageAdapter.languages_of(type(toolset)):
            self._recorded.append(toolset)

    def write_all(self) -> list[Path]:
        """Write every recorded toolset, with the connection and the browser-safe code they share."""
        if not self._recorded:
            return []
        peers = self._typescript_toolsets()
        root = self.path / _FOLDER / _TYPESCRIPT
        shared = {_CONNECTION_FILE: self._connection(), _SHARED_FILE: self._template(_SHARED_FILE), _VIEWS_FILE: self._template(_VIEWS_FILE), _MANIFEST_FILE: _MANIFEST}
        files = {root / name: text for name, text in shared.items()}
        for peer in peers.values():
            files.update({root / Path(path): text for path, text in peer.render().items()})
        if _FILE_MANAGER in peers:
            files[root / _FILES_FILE] = self._file_views(peers[_FILE_MANAGER])
        return [self._written(path, text) for path, text in files.items()]

    def _file_views(self, file_manager: TypeScriptToolset) -> str:
        """The shared file views, importing the file manager's client from wherever its toolset was installed."""
        path = f"./{file_manager.file_path.with_suffix('').as_posix()}"
        return self._template(_FILES_FILE).replace("__FILE_MANAGER__", path)

    def _connection(self) -> str:
        """The connection starts cdd from this checkout with the Python running this install."""
        source_root = self.repo or Path.cwd().resolve()
        text = self._template(_CONNECTION_FILE)
        return text.replace("__SOURCE_ROOT__", json.dumps(str(source_root))).replace("__PYTHON__", json.dumps(sys.executable))

    def _template(self, file_name: str) -> str:
        note = _NOTE.format(source="the installer")
        return f"{note}\n{(_TEMPLATES / file_name).read_text(encoding='utf-8')}"

    def _typescript_toolsets(self) -> dict[str, TypeScriptToolset]:
        peers: dict[str, TypeScriptToolset] = {}
        for toolset in self._recorded:
            tools = toolset.tools_for(InstallDestination.MCP)
            peers[type(toolset).__name__] = TypeScriptToolset(toolset, tools, self.folder_for(toolset), peers)
        return peers

    def _written(self, path: Path, text: str) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        self.track_write(path)
        return path


def _identity_fields(identity: tuple[str, ...]) -> list[str]:
    """The names an object is addressed by stay private, so a data field of the same name keeps its public getter."""
    return [f"  readonly #{Name(name).camel}: string" for name in identity] + ([""] if identity else [])


def _identity_kept(identity: tuple[str, ...]) -> list[str]:
    return [f"    this.#{Name(name).camel} = {Name(name).camel}" for name in identity]
